def load():
    return json.load(open(SRC, encoding="utf-8"))


data = load()
by_tag = {it["tag"]: it for it in data["intents"]}

removed_within = collections.Counter()
removed_cross = []
added = collections.Counter()
seen_global = {}

for intent in data["intents"]:
    tag = intent["tag"]
    original = list(intent["patterns"])
    extra = ADDITIONS.get(tag, [])
    kept, seen_local = [], set()
    for i, pat in enumerate(original + extra):
        norm = normalize(pat)
        if not norm:
            continue
        key = dedupe_key(norm)
        if key in seen_local:
            if i < len(original):
                removed_within[tag] += 1
            continue
        if key in seen_global:
            removed_cross.append((norm, tag, seen_global[key]))
            continue
        seen_local.add(key)
        seen_global[key] = tag
        kept.append(norm)
        if i >= len(original):
            added[tag] += 1
    intent["patterns"] = kept

json.dump(data, open(SRC, "w", encoding="utf-8"), indent=2, ensure_ascii=False)

