SRC = sys.argv[1] if len(sys.argv) > 1 else "agent_intents.json"

TRANS = {
    "’": "'", "‘": "'",      # curly single quotes
    "“": '"', "”": '"',      # curly double quotes
    "–": "-", "—": "-",      # en / em dash
    "…": "...",                    # ellipsis
    " ": " ",                      # non-breaking space
}


def normalize(text):
    for a, b in TRANS.items():
        text = text.replace(a, b)
    return " ".join(text.split())


def dedupe_key(text):
    t = text.lower()
    for c in ["?", ".", "!", '"']:
        t = t.replace(c, "")
    return " ".join(t.split())


