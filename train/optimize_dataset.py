"""Reproducible dataset optimizer for train/agent_intents.json.

Run:  python optimize_dataset.py agent_intents.json

What it does, in order:
  1. Normalizes typographic punctuation to ASCII (curly quotes/apostrophes,
     en/em dashes, ellipsis, non-breaking space) so training text matches the
     straight-quote text users type and the punctuation stripping in classify().
     Degree/superscript symbols in Math are intentionally preserved.
  2. Appends the curated ADDITIONS below to grow every class and fill known
     coverage gaps (e.g. smart-home / timer / system Utility commands like
     "Turn on my lights at 10:45", which previously misclassified).
  3. Removes exact duplicates (case-insensitive, punctuation-stripped) within a
     tag and across tags, so nothing is double-counted and no pattern maps to
     two labels.

No classes are removed and no existing patterns are dropped except exact dups.
The 16 tags are preserved exactly (FreeClaw's _TAG_SETTINGS depends on them),
and each intent's "responses" list is left untouched.
"""
